// m2tgpx4recomp: static recompiler for the Model 2C TGPx4 (MB86235) program.
//
//   m2tgpx4recomp TGPX4_UPLOAD.bin OUT.cpp
//
// The TGPx4 runs from program RAM the i960 fills at boot: 64-bit
// instructions written through the copro FIFO port as 32-bit halves, low
// half first, while coproctl bit 31 is set (MAME model2c copro_fifo_w;
// 8,192 halves, 4,096 instructions, for Sega Touring Car Championship).
// scripts/m2import.py extracts them from the game's ROM as tgpx4_upload.bin,
// little-endian 32-bit words. This tool turns every instruction into native
// C++: one label per program address, each running one step of MAME's
// execute_run (the delay slot, the repeat counter, the FIFO stall) around
// MAME's execute_op for the instruction (src/runtime/tgpx4/mame/ops.inc),
// with the opcode a constant the compiler folds into it. The next
// instruction is execute_run's next address: a direct goto when it is the
// next address in the same chunk of the program (16 addresses, one
// function), the dispatch otherwise (branches, calls, returns, delay slots).
//
// An instruction that pops the empty input FIFO stalls as MAME's does (it
// reads 0, its side effects but the registers it loads are held back) and
// returns from run(), to run again from the same address once the board has
// pushed a word; MAME's TGPx4 spins re-running it, which changes nothing
// more, for the stalling instructions of the programs seen (none writes the
// output FIFO or the external bus). Nothing is interpreted at run time; an
// opcode MAME does not implement compiles to MAME's error.
//
// The output is derived from the game: write it under build/ (git-ignored),
// never commit it.

#include <algorithm>
#include <cstdint>
#include <cstdio>
#include <fstream>
#include <iterator>
#include <sstream>
#include <stdexcept>
#include <string>
#include <vector>

namespace {

uint32_t crc32(const std::vector<uint8_t> &d) {
    uint32_t c = 0xffffffffu;
    for (uint8_t x : d) {
        c ^= x;
        for (int k = 0; k < 8; k++) c = (c >> 1) ^ (0xedb88320u & (0u - (c & 1)));
    }
    return ~c;
}

std::string hx(uint64_t v) {
    char b[24];
    std::snprintf(b, sizeof b, "0x%llx", (unsigned long long)v);
    return b;
}

} // namespace

int main(int argc, char **argv) {
    if (argc != 3) {
        std::fprintf(stderr, "usage: m2tgpx4recomp TGPX4_UPLOAD.bin OUT.cpp\n");
        return 2;
    }
    try {
        std::ifstream f(argv[1], std::ios::binary);
        if (!f) throw std::runtime_error(std::string("cannot open ") + argv[1]);
        const std::vector<uint8_t> raw{std::istreambuf_iterator<char>(f), {}};
        if (raw.empty() || raw.size() % 8) throw std::runtime_error("the upload is not a whole number of 64-bit instructions");
        const size_t n = raw.size() / 8;
        if (n > 0x1000) throw std::runtime_error("the upload is larger than program RAM (4,096 instructions)");
        std::vector<uint64_t> prog(n, 0);
        for (size_t i = 0; i < n; i++)
            for (int b = 0; b < 8; b++) prog[i] |= uint64_t(raw[8 * i + b]) << (8 * b);

        constexpr size_t kChunk = 16;
        const size_t chunks = (n + kChunk - 1) / kChunk;
        std::ostringstream o;
        o << "// Generated by tools/m2tgpx4recomp from the TGPx4 program the i960 uploads.\n"
             "// Derived from the game's ROM: never commit it.\n"
             "#include \"runtime/tgpx4/tgpx4_gen.h\"\n"
             "#include \"runtime/tgpx4/tgpx4_impl.h\"\n\n"
             "namespace rt::tgpx4gen {\n\n"
             "const uint32_t upload_words = "
          << n * 2 << ";\nconst uint32_t upload_crc32 = " << hx(crc32(raw)) << "u;\nconst uint32_t program_size = " << n
          << ";\n\n"
             "namespace {\n\n"
             "enum class Next { Dispatch, Wait, Budget };\n\n";
        for (size_t k = 0; k < chunks; k++) {
            const size_t lo = k * kChunk, hi = std::min(n, lo + kChunk);
            o << "Next chunk" << k << "(rt::tgpx4::Tgpx4 &t, uint32_t pc, uint64_t &budget) {\n"
                 "    auto *const c = t.m_core;\n"
                 "    switch (pc) {\n";
            for (size_t i = lo; i < hi; i++) o << "    case " << hx(i) << ": goto L" << std::hex << i << std::dec << ";\n";
            o << "    default: return Next::Dispatch;\n    }\n";
            for (size_t i = lo; i < hi; i++) {
                o << "L" << std::hex << i << std::dec << ": {\n"
                  << "    t.step(" << hx(i) << "u);\n"
                  << "    t.execute_op(" << hx(prog[i]) << "ull);\n"
                  << "    t.count++;\n"
                     "    if (c->cur_fifo_state.has_stalled) return Next::Wait;\n"
                     "    if (--budget == 0) return Next::Budget;\n";
                if (i + 1 < hi) o << "    if (c->pc == " << hx(i + 1) << "u) goto L" << std::hex << i + 1 << std::dec << ";\n";
                o << "    return Next::Dispatch;\n}\n";
            }
            o << "}\n\n";
        }
        o << "using Chunk = Next (*)(rt::tgpx4::Tgpx4 &, uint32_t, uint64_t &);\n"
             "const Chunk kChunks[] = {\n";
        for (size_t k = 0; k < chunks; k++) o << "    chunk" << k << ",\n";
        o << "};\n\n} // namespace\n\n"
             "Stop run(rt::tgpx4::Tgpx4 &t, uint64_t budget) {\n"
             "    auto *const c = t.m_core;\n"
             "    if (c->cur_fifo_state.has_stalled && t.bus->in_empty()) return Stop::Wait; // as MAME's spinning: no change\n"
             "    for (;;) {\n"
             "        const uint32_t pc = t.next_pc() & 0xfff; // the program space's 12 address bits\n"
             "        if (pc >= "
          << n << "u) throw rt::tgpx4::Tgpx4Fatal(\"TGPx4: execution left the recompiled program\", pc);\n"
             "        switch (kChunks[pc / "
          << kChunk << "](t, pc, budget)) {\n"
             "        case Next::Dispatch: break;\n"
             "        case Next::Wait: return Stop::Wait;\n"
             "        case Next::Budget: return Stop::Budget;\n"
             "        }\n"
             "    }\n"
             "}\n\n} // namespace rt::tgpx4gen\n";

        std::ofstream out(argv[2]);
        out << o.str();
        if (!out) throw std::runtime_error(std::string("cannot write ") + argv[2]);
        std::printf("m2tgpx4recomp: %zu instructions\n", n);
        return 0;
    } catch (const std::exception &e) {
        std::fprintf(stderr, "m2tgpx4recomp: %s\n", e.what());
        return 1;
    }
}
